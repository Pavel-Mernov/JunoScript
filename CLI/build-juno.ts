import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, extname, relative, resolve } from 'node:path'
import { parse, Statement } from '../Lexer/parser'
import { analyze } from '../vscode-junoscript/src/language'

export type BuildOptions = {
    outFile?: string
    target?: 'js' | 'ts'
}

function modulePath(fromDirectory: string, target: string): string {
    const path = relative(fromDirectory, target).replace(/\\/g, '/')
    return path.startsWith('.') ? path : `./${path}`
}

function exportedNames(statements: Statement[]): { values: string[]; types: string[]; defaultName?: string } {
    const values = new Set<string>()
    const types = new Set<string>()
    let defaultName: string | undefined
    for (const statement of statements) {
        if (statement.kind !== 'Export') continue
        const declaration = statement.declaration
        const names = declaration.kind === 'Destructure'
            ? declaration.bindings.map(binding => binding.name)
            : declaration.kind === 'Import'
                ? [...(declaration.defaultImport ? [declaration.defaultImport] : []), ...declaration.namedImports]
                : 'name' in declaration ? [declaration.name] : []
        for (const name of names) {
            values.add(name)
            if (declaration.kind === 'TypeDeclaration') types.add(name)
            if (statement.default) defaultName = name
        }
    }
    return { values: [...values], types: [...types], defaultName }
}

export function buildJunoFile(file: string, options: BuildOptions = {}): string {
    const input = resolve(file)
    const target = options.target ?? (options.outFile && extname(options.outFile).toLowerCase() === '.ts' ? 'ts' : 'js')
    const output = resolve(options.outFile ?? input.replace(/\.jn$/i, target === 'ts' ? '.ts' : '.js'))
    if (input === output) throw new Error('Build output must be different from the input JN file')

    const source = readFileSync(input, 'utf8')
    const diagnostics = analyze(source, input)?.diagnostics ?? []
    if (diagnostics.length) {
        const details = diagnostics.map(item => `${input}:${item.line}:${item.column} - ${item.message}`).join('\n')
        throw new Error(`JunoScript diagnostics prevented build:\n${details}`)
    }
    const statements = parse(source, { filePath: input })
    const exports = exportedNames(statements)
    const runtime = resolve(__dirname, '../Runtime/interpreter.js')
    const runtimeImport = modulePath(dirname(output), runtime)
    const runtimeTypes = resolve(__dirname, '../../Runtime/interpreter')
    const runtimeTypeImport = modulePath(dirname(output), runtimeTypes)
    const sourceReference = modulePath(dirname(output), input)
    const banner = '// Generated by junode --build. Edit the .jn source instead.\n'

    const generated = target === 'js'
        ? `${banner}"use strict";\nconst path = require("node:path");\nconst { runBuiltModule } = require(${JSON.stringify(runtimeImport)});\nconst __junoSource = ${JSON.stringify(source)};\nconst __junoFilename = path.resolve(__dirname, ${JSON.stringify(sourceReference)});\nmodule.exports = runBuiltModule(__junoSource, __junoFilename);\n`
        : `${banner}import * as path from 'node:path'\nconst { runBuiltModule } = require(${JSON.stringify(runtimeImport)}) as typeof import(${JSON.stringify(runtimeTypeImport)})\n\nconst __junoSource = ${JSON.stringify(source)}\nconst __junoFilename = path.resolve(__dirname, ${JSON.stringify(sourceReference)})\nconst __junoModule = runBuiltModule(__junoSource, __junoFilename) as Record<string, any>\n\n${exports.values.filter(name => name !== exports.defaultName).map(name => `export const ${name} = __junoModule[${JSON.stringify(name)}]`).join('\n')}${exports.types.length ? `\n${exports.types.map(name => `export type ${name} = any`).join('\n')}` : ''}${exports.defaultName ? `\nexport default __junoModule[${JSON.stringify(exports.defaultName)}]\n` : '\n'}`

    writeFileSync(output, generated)
    return output
}
